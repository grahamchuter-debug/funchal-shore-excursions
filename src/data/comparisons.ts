export function getComparisonBySlug(slug: string): Comparison | undefined {
  return comparisons.find((c) => c.slug === slug);
}

export function getAllComparisonSlugs(): string[] {
  return comparisons.map((c) => c.slug);
}

export function getComparisonDisplayTitle(comparison: Comparison): string {
  if (comparison.kind === "versus" && comparison.optionA && comparison.optionB) {
    return `${comparison.optionA} vs ${comparison.optionB}`;
  }
  return comparison.title;
}
